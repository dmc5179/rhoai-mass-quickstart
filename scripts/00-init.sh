#!/usr/bin/env bash
#
# 00-init.sh - fetch the OpenShift installer and client for the current OCP 4.22
#              release (RHEL 9 / x86_64 builds) into bin/.
#
# Usage:
#   scripts/00-init.sh [--dir <path>] [--channel <name>] [--force]
#
# Options:
#   --dir <path>      Where to place the binaries (default: <repo>/bin)
#   --channel <name>  Mirror channel to pull from (default: stable-4.22)
#   --force           Re-download even if the binaries are already present
#   --skip-helm       Do not fetch helm
#
# Red Hat publishes helm on the same mirror, so it is fetched here too - the
# AutoShift charts in phase 50 need it. There is no argocd CLI on the mirror;
# OpenShift GitOps serves its own through a ConsoleCLIDownload once installed,
# so phase 50 fetches that from the cluster instead.
#
# PATH is deliberately left alone. The binaries are addressed by explicit path,
# via the generated bin/ocp-env.sh:
#
#   source bin/ocp-env.sh
#   "$OPENSHIFT_INSTALL" version
#   "$OC" get clusterversion
#
# Re-running is cheap: if the installed binaries already match the release
# published for the channel, the downloads are skipped.

set -euo pipefail

MIRROR_BASE="https://mirror.openshift.com/pub/openshift-v4/x86_64/clients/ocp"
HELM_BASE="https://mirror.openshift.com/pub/openshift-v4/x86_64/clients/helm/latest"
CHANNEL="${OCP_CHANNEL:-stable-4.22}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN_DIR="${ROOT}/bin"
FORCE=0
WANT_HELM=1

while [ $# -gt 0 ]; do
    case "$1" in
        --dir)       BIN_DIR="$(cd "$2" 2>/dev/null && pwd || echo "$2")"; shift 2 ;;
        --channel)   CHANNEL="$2"; shift 2 ;;
        --force)     FORCE=1; shift ;;
        --skip-helm) WANT_HELM=0; shift ;;
        -h|--help)   sed -n '2,24p' "${BASH_SOURCE[0]}"; exit 0 ;;
        *) echo "00-init.sh: unknown option '$1'" >&2; exit 2 ;;
    esac
done

# RHEL 9 / x86_64 builds. These filenames are unversioned on the mirror and
# always resolve to the newest z-stream in the channel.
CLIENT_TAR="openshift-client-linux-amd64-rhel9.tar.gz"
INSTALL_TAR="openshift-install-rhel9-amd64.tar.gz"

# The RHEL 9 installer archive ships its binary as 'openshift-install-fips':
# the dynamically linked build that is able to run in FIPS mode, and an
# ordinary installer otherwise. It is kept under that name rather than renamed,
# so it is obvious which build is in use.
INSTALLER_BIN="openshift-install-fips"

URL="${MIRROR_BASE}/${CHANNEL}"
echo "==> Channel: ${CHANNEL}"
echo "==> Target:  ${BIN_DIR}"

mkdir -p "$BIN_DIR"

# Scratch space for the downloads. Archives are untrusted input, so each one is
# unpacked into its own empty directory and only the expected binaries are
# copied out.
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "==> Fetching checksum manifest"
curl -fsSL -o "${WORK}/sha256sum.txt" "${URL}/sha256sum.txt"

# The release version is not in a machine-readable field anywhere in the channel
# directory, so derive it from a versioned filename in the manifest.
VERSION="$(sed -n 's/.*openshift-client-linux-\([0-9][0-9.]*\)\.tar\.gz$/\1/p' \
           "${WORK}/sha256sum.txt" | head -1)"
echo "==> Release: ${VERSION:-unknown}"

write_env_file() {
    cat > "${BIN_DIR}/ocp-env.sh" <<EOF
# Generated by init.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) for OCP ${VERSION:-unknown}.
#
# Explicit paths to the tools fetched by init.sh. PATH is not modified, so these
# never collide with an oc or openshift-install installed elsewhere on the host.
#
# Usage: source ocp-env.sh
OCP_BIN_DIR="${BIN_DIR}"
OCP_VERSION="${VERSION:-unknown}"
OC="\${OCP_BIN_DIR}/oc"
KUBECTL="\${OCP_BIN_DIR}/kubectl"
OPENSHIFT_INSTALL="\${OCP_BIN_DIR}/${INSTALLER_BIN}"
HELM="\${OCP_BIN_DIR}/helm"
export OCP_BIN_DIR OCP_VERSION OC KUBECTL OPENSHIFT_INSTALL HELM
EOF
    echo "==> Wrote ${BIN_DIR}/ocp-env.sh"
}

# --- helm -------------------------------------------------------------------
# Red Hat ships its own helm build; phase 50 and AutoShift's charts need it.
# Unlike the OCP clients this is a bare binary rather than a tarball, under a
# different path, with its own checksum manifest.
fetch_helm() {
    local want="helm-linux-amd64"
    if [ "$FORCE" -eq 0 ] && [ -x "${BIN_DIR}/helm" ]; then
        echo "==> helm already present ($("${BIN_DIR}/helm" version --short 2>/dev/null || echo unknown))"
        return 0
    fi
    echo "==> Downloading helm"
    curl -fSL --retry 3 --retry-delay 2 -o "${WORK}/${want}" "${HELM_BASE}/${want}"
    curl -fsSL -o "${WORK}/helm-sha256sum.txt" "${HELM_BASE}/sha256sum.txt"

    echo "    Verifying sha256"
    local expected actual
    expected="$(awk -v f="$want" '$2 == f {print $1}' "${WORK}/helm-sha256sum.txt")"
    if [ -z "$expected" ]; then
        echo "00-init.sh: ${want} has no entry in the helm sha256sum.txt" >&2
        exit 1
    fi
    actual="$(sha256sum "${WORK}/${want}" | awk '{print $1}')"
    if [ "$expected" != "$actual" ]; then
        echo "00-init.sh: checksum mismatch for ${want}" >&2
        echo "  expected: ${expected}" >&2
        echo "  actual:   ${actual}" >&2
        exit 1
    fi
    install -m 0755 "${WORK}/${want}" "${BIN_DIR}/helm"
    echo "==> Installed ${BIN_DIR}/helm ($("${BIN_DIR}/helm" version --short 2>/dev/null || echo unknown))"
}

# helm is independent of the OCP client version check below, which exits
# early when oc and the installer are already current.
[ "$WANT_HELM" -eq 1 ] && fetch_helm

# Decide whether there is anything to download.
if [ "$FORCE" -eq 0 ] \
   && [ -x "${BIN_DIR}/oc" ] && [ -x "${BIN_DIR}/${INSTALLER_BIN}" ] \
   && "${BIN_DIR}/${INSTALLER_BIN}" version 2>/dev/null | grep -qF "${VERSION}"; then
    echo "==> ${INSTALLER_BIN} and oc are already at ${VERSION}; skipping download"
    echo "    (use --force to re-download)"
    write_env_file
    exit 0
fi

for tarball in "$CLIENT_TAR" "$INSTALL_TAR"; do
    echo "==> Downloading ${tarball}"
    curl -fSL --retry 3 --retry-delay 2 -o "${WORK}/${tarball}" "${URL}/${tarball}"

    echo "    Verifying sha256"
    expected="$(awk -v f="$tarball" '$2 == f {print $1}' "${WORK}/sha256sum.txt")"
    if [ -z "$expected" ]; then
        echo "00-init.sh: ${tarball} has no entry in sha256sum.txt" >&2
        exit 1
    fi
    actual="$(sha256sum "${WORK}/${tarball}" | awk '{print $1}')"
    if [ "$expected" != "$actual" ]; then
        echo "00-init.sh: checksum mismatch for ${tarball}" >&2
        echo "  expected: ${expected}" >&2
        echo "  actual:   ${actual}" >&2
        exit 1
    fi

    echo "    Unpacking"
    unpack="${WORK}/unpack-${tarball%%.*}"
    mkdir -p "$unpack"
    tar -xzf "${WORK}/${tarball}" -C "$unpack"
done

# Copy out only the executables; the archives also carry a README.md that would
# otherwise land on top of anything already in BIN_DIR.
missing=""
for binary in oc kubectl "$INSTALLER_BIN"; do
    src="$(find "$WORK" -mindepth 2 -maxdepth 2 -type f -name "$binary" -print -quit)"
    if [ -n "$src" ]; then
        install -m 0755 "$src" "${BIN_DIR}/${binary}"
        echo "==> Installed ${BIN_DIR}/${binary}"
    elif [ "$binary" = "kubectl" ]; then
        :   # bundled with the client archive, but not worth failing over
    else
        missing="${missing} ${binary}"
    fi
done

if [ -n "$missing" ]; then
    echo "00-init.sh: could not find these binaries in the archives:${missing}" >&2
    exit 1
fi



write_env_file

echo
echo "Ready. Reference the tools by explicit path:"
echo
echo "    source ${BIN_DIR}/ocp-env.sh"
echo "    \"\$OPENSHIFT_INSTALL\" version"
echo "    \"\$OC\" version --client"
echo
